#!/usr/bin/env tsx
/**
 * Parse the TfNSW Household Travel Survey (HTS) "Data by LGA" workbooks into
 * src/lib/data/hts-lga-data.ts.
 *
 * Source: TfNSW Open Data — https://opendata.transport.nsw.gov.au/dataset/household-travel-survey
 * Coverage: Sydney Greater Metropolitan Area LGAs only (Greater Sydney, Central
 * Coast, Hunter, Illawarra, Shoalhaven, Wingecarribee), average weekday,
 * 2016/17–2019/20 and 2021/22 onwards (no 2020/21 LGA estimates).
 *
 * Usage:
 *   npm run parse:hts                         # resolve + download current files via CKAN
 *   npm run parse:hts -- --file a.xlsx --file b.xlsx   # parse local copies
 */

import * as fs from 'fs';
import * as path from 'path';
import * as XLSX from 'xlsx';
import { LGA_CODE_MAP } from '../src/lib/abs-fetchers';
import { parseHtsWorkbookRows, type HTSRawRows } from '../src/lib/hts-parser';

const CKAN_PACKAGE_URL =
  'https://opendata.transport.nsw.gov.au/data/api/3/action/package_show?id=household-travel-survey';
const OUTPUT_PATH = path.join(process.cwd(), 'src', 'lib', 'data', 'hts-lga-data.ts');

interface CkanResource { name: string; url: string; format: string }

async function resolveLgaWorkbookUrls(): Promise<string[]> {
  const res = await fetch(CKAN_PACKAGE_URL);
  if (!res.ok) throw new Error(`CKAN package_show failed: HTTP ${res.status}`);
  const body = await res.json() as { result: { resources: CkanResource[] } };
  return body.result.resources
    .filter(r => /data-by-lga/i.test(r.url) && /xlsx/i.test(r.format || r.url))
    .map(r => r.url);
}

async function loadWorkbook(source: string): Promise<{ wb: XLSX.WorkBook; label: string }> {
  if (/^https?:\/\//.test(source)) {
    console.log(`  Downloading ${source}`);
    const res = await fetch(source);
    if (!res.ok) throw new Error(`Download failed (${res.status}): ${source}`);
    return { wb: XLSX.read(Buffer.from(await res.arrayBuffer()), { type: 'buffer' }), label: source.split('/').pop() ?? source };
  }
  return { wb: XLSX.readFile(source), label: path.basename(source) };
}

function sheetRows(wb: XLSX.WorkBook, name: string): Record<string, unknown>[] {
  const sheet = wb.Sheets[name];
  if (!sheet) return [];
  // Lower-case all headers: the 2016–2019 file uses lower case, 2021+ upper case.
  return XLSX.utils.sheet_to_json<Record<string, unknown>>(sheet, { defval: null }).map(row =>
    Object.fromEntries(Object.entries(row).map(([k, v]) => [k.toLowerCase(), v])),
  );
}

async function main() {
  const args = process.argv.slice(2);
  const files = args.flatMap((a, i) => (a === '--file' ? [args[i + 1]] : []));
  const sources = files.length > 0 ? files : await resolveLgaWorkbookUrls();
  if (sources.length === 0) throw new Error('No HTS "data by LGA" workbooks found');

  const raw: HTSRawRows = { mode: [], purpose: [], demographics: [] };
  const sourceLabels: string[] = [];
  for (const source of sources) {
    const { wb, label } = await loadWorkbook(source);
    raw.mode.push(...sheetRows(wb, 'Data by Mode'));
    raw.purpose.push(...sheetRows(wb, 'Data by Purpose'));
    raw.demographics.push(...sheetRows(wb, 'Demographics'));
    sourceLabels.push(label);
  }

  const knownCodes = new Set(Object.values(LGA_CODE_MAP));
  const { byLgaCode, unmatched } = parseHtsWorkbookRows(raw, knownCodes);
  if (unmatched.length > 0) console.warn(`  ⚠ HTS LGAs with no LGA_CODE_MAP entry (skipped): ${unmatched.join(', ')}`);

  const header = `/**
 * AUTO-GENERATED by scripts/parse-hts.ts — do not edit by hand.
 * Source: TfNSW Household Travel Survey, Data by LGA (${sourceLabels.join('; ')})
 * https://opendata.transport.nsw.gov.au/dataset/household-travel-survey
 * Generated: ${new Date().toISOString()}
 */

import type { HTSLgaData } from '../hts-parser';

`;
  // One line per LGA keeps the file compact and diffs readable.
  const entries = Object.keys(byLgaCode).sort().map(code => `  ${JSON.stringify(code)}: ${JSON.stringify(byLgaCode[code])},`);
  const body = `export const HTS_LGA_DATA: Record<string, HTSLgaData> = {\n${entries.join('\n')}\n};\n`;
  fs.writeFileSync(OUTPUT_PATH, header + body);
  console.log(`  ✅ ${Object.keys(byLgaCode).length} LGAs written to ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});
