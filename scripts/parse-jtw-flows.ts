#!/usr/bin/env tsx
/**
 * Parse an ABS TableBuilder export of Census journey-to-work flows between
 * LGAs into src/lib/data/jtw-flows-data.ts.
 *
 * There is no open (login-free) LGA→LGA flow file for Census 2021: TfNSW has
 * not published JTW 2021 and withdrew JTW 2016, and the ABS Data API has no
 * place-of-work dataflows. Build the table in ABS TableBuilder (free account):
 *
 *   Dataset:  2021 Census - Employment, Income and Education
 *   Rows:     LGA (UR)   — Place of Usual Residence, all NSW LGAs
 *   Columns:  LGA (POW)  — Place of Work, all LGAs (incl. interstate)
 *   Counting: Persons Place of Usual Residence
 *   Download: "Comma Separated Value (.csv)"
 *
 * Usage:
 *   npm run parse:jtw-flows -- path/to/tablebuilder-export.csv
 */

import * as fs from 'fs';
import * as path from 'path';
import { LGA_CODE_MAP } from '../src/lib/abs-fetchers';
import { SAMPLE_AREAS } from '../src/lib/data/sample-areas';
import { parseTableBuilderCsv, createLgaResolver, summariseFlows } from '../src/lib/jtw-flows';

const OUTPUT_PATH = path.join(process.cwd(), 'src', 'lib', 'data', 'jtw-flows-data.ts');

function main() {
  const input = process.argv[2];
  if (!input) {
    console.error('Usage: npm run parse:jtw-flows -- <TableBuilder CSV export>');
    process.exit(1);
  }

  const flows = parseTableBuilderCsv(fs.readFileSync(input, 'utf-8'));
  if (flows.length === 0) throw new Error(`No flows found in ${input} — is it a TableBuilder CSV with LGA (UR) × LGA (POW)?`);

  const resolve = createLgaResolver(SAMPLE_AREAS, LGA_CODE_MAP);
  const areaNameByCode = new Map(SAMPLE_AREAS.filter(a => LGA_CODE_MAP[a.id]).map(a => [LGA_CODE_MAP[a.id], a.name]));
  const { byLgaCode, unmatched } = summariseFlows(flows, resolve, code => areaNameByCode.get(code));
  if (unmatched.length > 0) console.warn(`  ⚠ Residence LGAs with no LGA_CODE_MAP match (skipped): ${unmatched.join(', ')}`);

  const missing = Object.entries(LGA_CODE_MAP).filter(([id, code]) => id.startsWith('lga_') && !byLgaCode[code]).map(([id]) => id);
  if (missing.length > 0) console.warn(`  ⚠ LGAs with no flows in the export: ${missing.join(', ')}`);

  const entries = Object.keys(byLgaCode).sort().map(code => `  ${JSON.stringify(code)}: ${JSON.stringify(byLgaCode[code])},`);
  fs.writeFileSync(OUTPUT_PATH, `/**
 * AUTO-GENERATED by scripts/parse-jtw-flows.ts — do not edit by hand.
 * Source: ABS Census 2021 TableBuilder, LGA (UR) × LGA (POW) (${path.basename(input)})
 * Generated: ${new Date().toISOString()}
 */

import type { JTWFlowSummary } from '../jtw-flows';

export const JTW_FLOWS_CENSUS_YEAR: number | null = 2021;

export const JTW_FLOWS_DATA: Record<string, JTWFlowSummary> = {
${entries.join('\n')}
};
`);
  console.log(`  ✅ ${flows.length} flows → ${Object.keys(byLgaCode).length} LGAs written to ${path.relative(process.cwd(), OUTPUT_PATH)}`);
}

main();
