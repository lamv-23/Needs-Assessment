#!/usr/bin/env tsx
/**
 * Fetch the 644 NSW SA2 boundaries (ASGS 2021) from the ABS ArcGIS service and
 * write the three SA2 geography outputs:
 *
 *   public/geo/sa2-nsw.json         — full-resolution GeoJSON, properties { code, name }.
 *                                     Gitignored intermediate (the simplified copy is what ships).
 *   public/geo/sa2-nsw-simple.json  — the same, simplified with mapshaper (as `npm run build:geo`
 *                                     does for the LGAs), for the map.
 *   src/lib/data/sa2-areas.ts       — SA2_AREAS: code, name, SA3 / SA4 / GCCSA names and area (km²).
 *
 * Source: https://geo.abs.gov.au/arcgis/rest/services/ASGS2021/SA2/FeatureServer/0
 * (state_code_2021 = '1' is NSW, which includes the special-purpose SA2s).
 *
 * Run: npm run fetch:sa2-boundaries   (needs network; ~1 min)
 */

import * as fs from 'fs';
import * as path from 'path';
import { execFileSync } from 'child_process';
import { queryFeatureServer } from '../src/lib/arcgis';

const SA2_LAYER_URL = 'https://geo.abs.gov.au/arcgis/rest/services/ASGS2021/SA2/FeatureServer/0';
const NSW_STATE_CODE = '1';
const EXPECTED_SA2_COUNT = 644;
// The ABS publishes these two special-purpose SA2s with attributes but no geometry: they are residents who
// have no place on the map. They stay in the registry and the GeoJSON (geometry null), so the file holds
// all 644; Leaflet skips null-geometry features. Any other SA2 without geometry is an error.
const NO_GEOMETRY_SA2_CODES = new Set(['197979799', '199999499']);

const GEO_DIR = path.join(process.cwd(), 'public/geo');
const FULL_PATH = path.join(GEO_DIR, 'sa2-nsw.json');
const SIMPLE_PATH = path.join(GEO_DIR, 'sa2-nsw-simple.json');
const AREAS_PATH = path.join(process.cwd(), 'src/lib/data/sa2-areas.ts');

const SIMPLIFY = '3%';
const MAX_SIMPLE_BYTES = 4 * 1024 * 1024;
const AREA_DECIMALS = 4;

interface Sa2Record {
  code: string;
  name: string;
  sa3Name: string;
  sa4Name: string;
  gccsaName: string;
  areaKm2: number;
}

function text(properties: GeoJSON.GeoJsonProperties, field: string): string {
  const value = properties?.[field];
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`SA2 ${properties?.sa2_code_2021 ?? '?'} has no ${field}`);
  }
  return value.trim();
}

function toRecord(f: GeoJSON.Feature): Sa2Record {
  const p = f.properties;
  const area = p?.area_albers_sqkm;
  return {
    code: text(p, 'sa2_code_2021'),
    name: text(p, 'sa2_name_2021'),
    sa3Name: text(p, 'sa3_name_2021'),
    sa4Name: text(p, 'sa4_name_2021'),
    gccsaName: text(p, 'gccsa_name_2021'),
    // Special-purpose SA2s (offshore / shipping, no usual address) have no land area.
    areaKm2: typeof area === 'number' ? Number(area.toFixed(AREA_DECIMALS)) : 0,
  };
}

/** The GeoJSON file, one feature per line (the same layout mapshaper writes) to keep diffs and memory sane. */
function writeFeatureCollection(file: string, features: GeoJSON.Feature[]): void {
  const lines = features.map(f => JSON.stringify(f));
  fs.writeFileSync(file, `{"type":"FeatureCollection", "features": [\n${lines.join(',\n')}\n]}\n`);
}

function renderAreasModule(records: Sa2Record[]): string {
  const lines = records.map(r => `  ${JSON.stringify(r)},`);
  return [
    '// Auto-generated by scripts/fetch-sa2-boundaries.ts from the ABS ASGS2021 SA2 FeatureServer (NSW, 644 SA2s).',
    '// Do not edit by hand — run `npm run fetch:sa2-boundaries`.',
    '// One record per line, sorted by SA2 code.',
    '',
    'export interface Sa2Area {',
    '  /** 9-digit ASGS 2021 SA2 code; NSW codes start with 1. */',
    '  code: string;',
    '  name: string;',
    '  sa3Name: string;',
    '  sa4Name: string;',
    '  gccsaName: string;',
    '  /** Land area from the ABS (Albers equal-area), km². 0 for the special-purpose SA2s. */',
    '  areaKm2: number;',
    '}',
    '',
    'export const SA2_AREAS: Sa2Area[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}

async function main() {
  console.log(`Fetching NSW SA2 boundaries from ${SA2_LAYER_URL} ...`);
  const features = await queryFeatureServer(SA2_LAYER_URL, {
    where: `state_code_2021='${NSW_STATE_CODE}'`,
    outFields: ['sa2_code_2021', 'sa2_name_2021', 'sa3_name_2021', 'sa4_name_2021', 'gccsa_name_2021', 'area_albers_sqkm'],
    returnGeometry: true,
  });
  console.log(`  ${features.length} features`);

  const rows = features
    .map(f => ({ feature: f, record: toRecord(f) }))
    .sort((a, b) => a.record.code.localeCompare(b.record.code));

  // Fail before writing anything if the layer is not what the rest of the app assumes.
  if (rows.length !== EXPECTED_SA2_COUNT) {
    throw new Error(`Expected ${EXPECTED_SA2_COUNT} NSW SA2s, the service returned ${rows.length}`);
  }
  if (new Set(rows.map(r => r.record.code)).size !== rows.length) throw new Error('Duplicate SA2 codes in the response');
  const badCodes = rows.filter(r => !/^1\d{8}$/.test(r.record.code)).map(r => r.record.code);
  if (badCodes.length) throw new Error(`Not NSW SA2 codes: ${badCodes.join(', ')}`);
  const noGeometry = rows.filter(r => !r.feature.geometry).map(r => r.record.code);
  const unexpected = noGeometry.filter(code => !NO_GEOMETRY_SA2_CODES.has(code));
  if (unexpected.length) throw new Error(`SA2s without geometry: ${unexpected.join(', ')}`);
  console.log(`  ${noGeometry.length} special-purpose SA2s have no geometry: ${noGeometry.join(', ')}`);

  const geoFeatures: GeoJSON.Feature[] = rows.map(({ feature, record }) => ({
    type: 'Feature',
    geometry: feature.geometry,
    properties: { code: record.code, name: record.name },
  }));
  writeFeatureCollection(FULL_PATH, geoFeatures);
  console.log(`Wrote ${path.relative(process.cwd(), FULL_PATH)} (${(fs.statSync(FULL_PATH).size / 1e6).toFixed(1)} MB)`);

  console.log(`Simplifying to ${SIMPLIFY} with mapshaper ...`);
  execFileSync(
    'npx',
    ['mapshaper', FULL_PATH, '-simplify', SIMPLIFY, 'keep-shapes', '-o', 'precision=0.0001', SIMPLE_PATH],
    { stdio: 'inherit' },
  );
  const simpleBytes = fs.statSync(SIMPLE_PATH).size;
  console.log(`Wrote ${path.relative(process.cwd(), SIMPLE_PATH)} (${(simpleBytes / 1e6).toFixed(2)} MB)`);
  if (simpleBytes >= MAX_SIMPLE_BYTES) {
    throw new Error(`${path.basename(SIMPLE_PATH)} is ${simpleBytes} bytes, over the ${MAX_SIMPLE_BYTES} limit`);
  }

  fs.writeFileSync(AREAS_PATH, renderAreasModule(rows.map(r => r.record)));
  console.log(`Wrote ${path.relative(process.cwd(), AREAS_PATH)} (${rows.length} SA2s)`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
