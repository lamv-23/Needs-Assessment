/**
 * Get all employment projections for a given lgaId
 */
export function getEmploymentProjections(lgaId: string): EmploymentProjection[] {
  return tzp24EmploymentByLGA.filter(e => e.lgaId === lgaId).sort((a, b) => a.year - b.year);
}

/**
 * Get employment for a specific lgaId and year (nearest available year)
 */
export function getEmploymentForYear(lgaId: string, year: number): number | null {
  const rows = getEmploymentProjections(lgaId);
  if (!rows.length) return null;
  // Exact match first
  const exact = rows.find(r => r.year === year);
  if (exact) return exact.totalEmployed;
  // Nearest year
  const nearest = rows.reduce((prev, curr) =>
    Math.abs(curr.year - year) < Math.abs(prev.year - year) ? curr : prev
  );
  return nearest.totalEmployed;
}

